public class Example3 {
    public static void main(String[] args) {
        
        // WHILE LOOP 

        // var i = 1;
        int i = 1;

        while (i <= 10) {
            System.out.println("Do Something here!");
            i = i + 1; // leaving this statement will result in an unterminating loop
        }
        System.out.println("AFTER WHILE LOOP!");
    }
}

public class Example5 {
    public static void main(String[] args) {
        // switch case/statement

        // varibale has to be either an int, char, String, enum

        int x = 10;

        switch (x) {
            case 1:
                System.out.println("A");
                break;
            case 10: 
                System.out.println("B");
                break;
        
            default:
                System.out.println("Default Value");
                break;
        }

    }
}
